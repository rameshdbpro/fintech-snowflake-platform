------------------------------------------------------------------ 7. retention guidance
-- RAW            : keep 13 months online (synthetic here); archive older batches to an external stage.
-- AUDIT          : >= 7 days Time Travel (set in 00), keep rows 7 years if used for regulatory evidence.
-- CORE/MARTS     : rebuildable from RAW; 1 day Time Travel is enough (DEV/TEST), 7 days PROD.
-- DQ_FAILURES    : truncate monthly (dbt --store-failures rewrites per run).
-- Transient work : OPS.GEN_* are TRANSIENT (no Fail-safe cost).
-- Data subject requests: delete from RAW.CUSTOMERS / KYC by customer_id, then
--   dbt build -s cnl_party_customer+ ; Time Travel limits how long deleted data persists.
