CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MP_PII_NAME AS (val VARCHAR) RETURNS VARCHAR ->
  CASE WHEN IS_ROLE_IN_SESSION('FINTECH_KYC_OFFICER') OR IS_ROLE_IN_SESSION('FINTECH_TRANSFORMER') THEN val
       WHEN val IS NULL THEN NULL
       ELSE LEFT(val, 1) || '*** ' || LEFT(SPLIT_PART(val, ' ', -1), 1) || '***' END
  COMMENT = 'Initials only unless KYC officer';

CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MP_PII_EMAIL AS (val VARCHAR) RETURNS VARCHAR ->
  CASE WHEN IS_ROLE_IN_SESSION('FINTECH_KYC_OFFICER') OR IS_ROLE_IN_SESSION('FINTECH_TRANSFORMER') THEN val
       WHEN val IS NULL THEN NULL
       ELSE '*****@' || SPLIT_PART(val, '@', 2) END;

CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MP_PII_PHONE AS (val VARCHAR) RETURNS VARCHAR ->
  CASE WHEN IS_ROLE_IN_SESSION('FINTECH_KYC_OFFICER') OR IS_ROLE_IN_SESSION('FINTECH_TRANSFORMER') THEN val
       WHEN val IS NULL THEN NULL
       ELSE '******' || RIGHT(val, 4) END;

CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MP_PII_DATE AS (val DATE) RETURNS DATE ->
  CASE WHEN IS_ROLE_IN_SESSION('FINTECH_KYC_OFFICER') OR IS_ROLE_IN_SESSION('FINTECH_TRANSFORMER') THEN val
       ELSE DATE_TRUNC('year', val) END
  COMMENT = 'Birth year only unless KYC officer';

CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MP_KYC_RESTRICTED AS (val VARCHAR) RETURNS VARCHAR ->
  CASE WHEN IS_ROLE_IN_SESSION('FINTECH_KYC_OFFICER') OR IS_ROLE_IN_SESSION('FINTECH_TRANSFORMER') THEN val ELSE NULL END;

CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MP_PAN AS (val VARCHAR) RETURNS VARCHAR ->
  CASE WHEN IS_ROLE_IN_SESSION('FINTECH_KYC_OFFICER') OR IS_ROLE_IN_SESSION('FINTECH_TRANSFORMER') THEN val
       WHEN val IS NULL THEN NULL
       ELSE 'XXXXX' || RIGHT(val, 5) END;

-- Row access: global roles see all regions; regional roles see their mapped regions
CREATE ROW ACCESS POLICY IF NOT EXISTS GOVERNANCE.RAP_MERCHANT_REGION AS (region VARCHAR) RETURNS BOOLEAN ->
  IS_ROLE_IN_SESSION('FINTECH_ANALYST')
  OR IS_ROLE_IN_SESSION('FINTECH_TRANSFORMER')
  OR IS_ROLE_IN_SESSION('FINTECH_AI_USER')
  OR IS_ROLE_IN_SESSION('FINTECH_OPS')
  OR IS_ROLE_IN_SESSION('FINTECH_DEPLOYER')
  OR EXISTS (SELECT 1 FROM CONFIG.ROW_ACCESS_MAP m
             WHERE m.REGION = region AND IS_ROLE_IN_SESSION(m.ROLE_NAME))
  COMMENT = 'Regional analysts limited via CONFIG.ROW_ACCESS_MAP (runtime-configurable)';

-- dbt (TRANSFORMER) re-attaches policies after each build: needs APPLY on each policy
