GRANT APPLY ON MASKING POLICY GOVERNANCE.MP_PII_EMAIL      TO ROLE FINTECH_TRANSFORMER;
GRANT APPLY ON MASKING POLICY GOVERNANCE.MP_PII_PHONE      TO ROLE FINTECH_TRANSFORMER;
GRANT APPLY ON MASKING POLICY GOVERNANCE.MP_PII_DATE       TO ROLE FINTECH_TRANSFORMER;
GRANT APPLY ON MASKING POLICY GOVERNANCE.MP_KYC_RESTRICTED TO ROLE FINTECH_TRANSFORMER;
GRANT APPLY ON ROW ACCESS POLICY GOVERNANCE.RAP_MERCHANT_REGION TO ROLE FINTECH_TRANSFORMER;

