   10_SECURITY_GOVERNANCE.SQL
   RBAC (least privilege), masking + row access policies, tags, service
   users, audit queries, retention guidance.
   Masking / row access policies and tags require Enterprise Edition or higher.
   On Standard Edition: skip section 2-3 and run dbt with
     --vars '{apply_governance_policies: false}'.

   Separation of duties
     FINTECH_DEPLOYER    owns every object; used only by CI deployments.
     FINTECH_TRANSFORMER runs dbt (creates models, cannot grant); service role only.
     FINTECH_LOADER      writes LANDING/RAW only.
     FINTECH_OPS         operates tasks/procedures, reads AUDIT.
     FINTECH_ANALYST     reads curated layers; PII masked; all regions.
     FINTECH_ANALYST_<REGION> reads curated layers; rows limited to region.
     FINTECH_KYC_OFFICER analyst + unmasked PII/KYC.
     FINTECH_AI_USER     Cortex Analyst / Intelligence over the semantic layer only.
     FINTECH_CONFIG_APPROVER approves configuration change requests.
   No passwords anywhere: service users authenticate with key pairs.
   ===================================================================== */
