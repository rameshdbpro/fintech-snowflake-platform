/* =====================================================================
   03_AUDIT_TABLES.SQL  -  execution, ingestion, DQ, dbt and change audit
   All timestamps UTC. Audit tables are append-only (no UPDATE grants
   to non-owner roles; see 10_security_governance.sql).
   ===================================================================== */
USE ROLE FINTECH_DEPLOYER;
SET DB_NAME = 'FINTECH_DEV';
USE DATABASE IDENTIFIER($DB_NAME);
USE SCHEMA AUDIT;

CREATE TABLE IF NOT EXISTS AUDIT.INGESTION_LOG (
    INGESTION_ID     VARCHAR(100) DEFAULT UUID_STRING(),
    BATCH_ID         VARCHAR(100) NOT NULL,
    TARGET_TABLE     VARCHAR(200) NOT NULL,
    LOAD_METHOD      VARCHAR(30)  COMMENT 'SYNTHETIC_SQL | COPY_INTO | SNOWSIGHT_UPLOAD | PROMOTE_LANDING',
    SOURCE_FILE_NAME VARCHAR(500),
    ROWS_LOADED      NUMBER(38,0),
    ROWS_REJECTED    NUMBER(38,0),
    STATUS           VARCHAR(20)  COMMENT 'SUCCESS | PARTIAL | FAILED',
    MESSAGE          VARCHAR(4000),
    STARTED_AT       TIMESTAMP_NTZ,
    FINISHED_AT      TIMESTAMP_NTZ DEFAULT SYSDATE(),
    EXECUTED_BY      VARCHAR(100)  DEFAULT CURRENT_USER(),
    EXECUTED_ROLE    VARCHAR(100)  DEFAULT CURRENT_ROLE()
);

CREATE TABLE IF NOT EXISTS AUDIT.INGESTION_REJECTS (
    REJECT_ID        VARCHAR(100) DEFAULT UUID_STRING(),
    BATCH_ID         VARCHAR(100),
    TARGET_TABLE     VARCHAR(200),
    SOURCE_FILE_NAME VARCHAR(500),
    ROW_NUMBER       NUMBER(38,0),
    COLUMN_NAME      VARCHAR(500),
    ERROR_CODE       VARCHAR(50),
    ERROR_MESSAGE    VARCHAR(4000),
    REJECTED_RECORD  VARCHAR(16777216),
    CAPTURED_AT      TIMESTAMP_NTZ DEFAULT SYSDATE()
);

CREATE TABLE IF NOT EXISTS AUDIT.CONTROL_TOTALS (
    CONTROL_ID       VARCHAR(100) DEFAULT UUID_STRING(),
    BATCH_ID         VARCHAR(100),
    CONTROL_POINT    VARCHAR(50)  COMMENT 'RAW_BATCH | SOURCE_TO_CANONICAL | CANONICAL_TO_FACT',
    OBJECT_NAME      VARCHAR(200),
    CURRENCY_CODE    VARCHAR(3),
    ROW_COUNT        NUMBER(38,0),
    AMOUNT_TOTAL     NUMBER(38,2),
    EXPECTED_ROWS    NUMBER(38,0),
    EXPECTED_AMOUNT  NUMBER(38,2),
    IS_BALANCED      BOOLEAN,
    CAPTURED_AT      TIMESTAMP_NTZ DEFAULT SYSDATE()
);

CREATE TABLE IF NOT EXISTS AUDIT.DUPLICATE_LOG (
    DETECTED_AT      TIMESTAMP_NTZ DEFAULT SYSDATE(),
    TARGET_TABLE     VARCHAR(200),
    DUPLICATE_KEY    VARCHAR(500),
    OCCURRENCES      NUMBER(38,0),
    FIRST_BATCH_ID   VARCHAR(100),
    LAST_BATCH_ID    VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS AUDIT.PROCEDURE_LOG (
    LOG_ID           VARCHAR(100) DEFAULT UUID_STRING(),
    PROCEDURE_NAME   VARCHAR(200),
    RUN_ID           VARCHAR(100),
    STEP             VARCHAR(200),
    STATUS           VARCHAR(20)  COMMENT 'STARTED | SUCCESS | FAILED | WARN',
    ROWS_AFFECTED    NUMBER(38,0),
    MESSAGE          VARCHAR(16777216),
    LOGGED_AT        TIMESTAMP_NTZ DEFAULT SYSDATE(),
    EXECUTED_BY      VARCHAR(100) DEFAULT CURRENT_USER(),
    QUERY_ID         VARCHAR(100) DEFAULT LAST_QUERY_ID()
);

CREATE TABLE IF NOT EXISTS AUDIT.DQ_RESULTS (
    DQ_RUN_ID        VARCHAR(100),
    RULE_ID          VARCHAR(100),
    CHECK_SOURCE     VARCHAR(20)  COMMENT 'RUNTIME_RULE | DBT_TEST | RECON',
    TARGET_OBJECT    VARCHAR(300),
    RULE_TYPE        VARCHAR(50),
    SEVERITY         VARCHAR(10),
    STATUS           VARCHAR(10)  COMMENT 'PASS | WARN | FAIL | ERROR',
    FAILING_ROWS     NUMBER(38,0),
    OBSERVED_VALUE   VARCHAR(200),
    THRESHOLD        VARCHAR(200),
    DETAILS          VARCHAR(4000),
    CHECKED_AT       TIMESTAMP_NTZ DEFAULT SYSDATE()
);

-- Written by dbt on-run-end hook (macros/audit/log_dbt_results.sql)
CREATE TABLE IF NOT EXISTS AUDIT.DBT_RUN_RESULTS (
    INVOCATION_ID    VARCHAR(100),
    DBT_COMMAND      VARCHAR(50),
    TARGET_NAME      VARCHAR(50),
    NODE_UNIQUE_ID   VARCHAR(500),
    NODE_NAME        VARCHAR(300),
    RESOURCE_TYPE    VARCHAR(30),
    STATUS           VARCHAR(30),
    FAILURES         NUMBER(38,0),
    ROWS_AFFECTED    NUMBER(38,0),
    EXECUTION_SECONDS FLOAT,
    MESSAGE          VARCHAR(4000),
    LOGGED_AT        TIMESTAMP_NTZ DEFAULT SYSDATE()
);

-- Written by dbt on-run-end hook (macros/audit/log_model_lineage.sql)
CREATE TABLE IF NOT EXISTS AUDIT.DBT_MODEL_LINEAGE (
    INVOCATION_ID    VARCHAR(100),
    NODE_NAME        VARCHAR(300),
    RESOURCE_TYPE    VARCHAR(30),
    SCHEMA_NAME      VARCHAR(100),
    MATERIALIZATION  VARCHAR(50),
    PARENT_NAME      VARCHAR(300),
    PARENT_TYPE      VARCHAR(30),
    LOGGED_AT        TIMESTAMP_NTZ DEFAULT SYSDATE()
);

CREATE TABLE IF NOT EXISTS AUDIT.DATA_PROFILE (
    PROFILE_RUN_ID   VARCHAR(100),
    TABLE_NAME       VARCHAR(300),
    COLUMN_NAME      VARCHAR(300),
    DATA_TYPE        VARCHAR(100),
    ROW_COUNT        NUMBER(38,0),
    NULL_COUNT       NUMBER(38,0),
    DISTINCT_COUNT   NUMBER(38,0),
    MIN_VALUE        VARCHAR(500),
    MAX_VALUE        VARCHAR(500),
    PROFILED_AT      TIMESTAMP_NTZ DEFAULT SYSDATE()
);

CREATE TABLE IF NOT EXISTS AUDIT.KPI_SNAPSHOT (
    SNAPSHOT_ID      VARCHAR(100) DEFAULT UUID_STRING(),
    CHANGE_ID        VARCHAR(100),
    PHASE            VARCHAR(10)  COMMENT 'BEFORE | AFTER | ADHOC',
    METRIC_NAME      VARCHAR(100),
    METRIC_VALUE     NUMBER(38,6),
    CAPTURED_AT      TIMESTAMP_NTZ DEFAULT SYSDATE()
);

CREATE TABLE IF NOT EXISTS AUDIT.CHANGE_LOG (
    LOG_ID           VARCHAR(100) DEFAULT UUID_STRING(),
    CHANGE_ID        VARCHAR(100),
    ACTION           VARCHAR(30)  COMMENT 'SUBMITTED | VALIDATED | REJECTED | APPROVED | APPLIED | ROLLED_BACK | VERIFIED',
    ACTOR            VARCHAR(100) DEFAULT CURRENT_USER(),
    ACTOR_ROLE       VARCHAR(100) DEFAULT CURRENT_ROLE(),
    DETAILS          VARIANT,
    LOGGED_AT        TIMESTAMP_NTZ DEFAULT SYSDATE()
);

CREATE TABLE IF NOT EXISTS AUDIT.CORTEX_USAGE_LOG (
    LOG_ID           VARCHAR(100) DEFAULT UUID_STRING(),
    USE_CASE         VARCHAR(100),
    MODEL_NAME       VARCHAR(100),
    INPUT_ROWS       NUMBER(38,0),
    EXECUTED_BY      VARCHAR(100) DEFAULT CURRENT_USER(),
    EXECUTED_ROLE    VARCHAR(100) DEFAULT CURRENT_ROLE(),
    LOGGED_AT        TIMESTAMP_NTZ DEFAULT SYSDATE()
);

-- Generated AI explanations are stored, never used as financial truth.
CREATE TABLE IF NOT EXISTS AUDIT.AI_EXCEPTION_EXPLANATION (
    EXCEPTION_ID     VARCHAR(200),
    EXCEPTION_TYPE   VARCHAR(50),
    MODEL_NAME       VARCHAR(100),
    EXPLANATION      VARCHAR(16777216),
    GENERATED_AT     TIMESTAMP_NTZ DEFAULT SYSDATE(),
    GENERATED_BY     VARCHAR(100) DEFAULT CURRENT_USER()
);
